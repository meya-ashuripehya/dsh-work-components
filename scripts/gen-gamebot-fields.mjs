// 从 src/components/gamebot/fields.mjs 生成 lib/client.js 里的 GameBot 字段（INPUT_FIELDS 片段 + FEATURES.keys）。
// 用法：node scripts/gen-gamebot-fields.mjs（改了 fields.mjs 后运行，再 npm run build）。
//       node scripts/gen-gamebot-fields.mjs --check：只校验 lib/client.js 是否与 fields.mjs 一致（不一致退出码 1，不写文件）。
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { GAME_FIELDS, settingKey } = await import(pathToFileURL(join(root, 'src', 'components', 'gamebot', 'fields.mjs')).href)
const file = join(root, 'lib', 'client.js')
const CHECK = process.argv.includes('--check')
const original = readFileSync(file, 'utf8')
let src = original

const rows = []
for (const [game, fields] of Object.entries(GAME_FIELDS)) {
  for (const f of fields) {
    const row = { key: settingKey(game, f.cfg), label: f.label, type: f.kind }
    if (f.options) row.options = f.options
    if (f.kind === 'password') row.placeholder = '（已保存则留空不变）'
    else if (f.def) row.placeholder = f.def
    row.desc = (f.desc ? f.desc + ' ' : '') + `GameBot 配置键 ${f.cfg}。`
    rows.push('  ' + JSON.stringify(row) + ',')
  }
}
// 标记本身不含行尾，CRLF / LF 都能命中；块的换行跟随文件既有风格。
// （旧版常量带 \n，在 CRLF 文件上永远命中不了，于是每次运行都追加一份重复区块。）
const MARK_START = '  /* <gamebot-fields> generated by scripts/gen-gamebot-fields.mjs */'
const MARK_END = '  /* </gamebot-fields> */'
const EOL = src.includes('\r\n') ? '\r\n' : '\n'
const block = MARK_START + EOL + rows.join(EOL) + EOL + MARK_END + EOL

/** 摘掉全部既有区块（历史重复的一并清掉），返回第一处标记的偏移。 */
function stripBlocks(text) {
  let first = -1
  for (;;) {
    const s = text.indexOf(MARK_START)
    if (s === -1) return { text, first }
    if (first === -1) first = s
    const e = text.indexOf(MARK_END, s)
    if (e === -1) return { text, first }
    let end = e + MARK_END.length
    if (text.startsWith('\r\n', end)) end += 2
    else if (text.startsWith('\n', end)) end += 1
    text = text.slice(0, s) + text.slice(end)
  }
}

const stripped = stripBlocks(src)
src = stripped.text
if (stripped.first !== -1) {
  src = src.slice(0, stripped.first) + block + src.slice(stripped.first)
} else {
  const anchor = src.match(/  \{ key: "gamebotUrl",[^\n]*\r?\n/)
  if (!anchor) throw new Error('gamebotUrl row not found')
  src = src.replace(anchor[0], anchor[0] + block)
}
for (const game of Object.keys(GAME_FIELDS)) {
  const keys = [`gamebot-${game}Enabled`, 'gamebotUrl', 'gamebotRoot', ...GAME_FIELDS[game].map((f) => settingKey(game, f.cfg))]
  const re = new RegExp(`(id: "gamebot-${game}",[\\s\\S]*?keys: )\\[[^\\]]*\\]`)
  if (!re.test(src)) throw new Error(`FEATURES gamebot-${game} not found`)
  src = src.replace(re, (_, a) => a + JSON.stringify(keys).replace(/","/g, '", "'))
}
if (CHECK) {
  if (src !== original) {
    console.error('lib/client.js GameBot fields are out of date: run node scripts/gen-gamebot-fields.mjs')
    process.exit(1)
  }
  console.log(`gamebot fields: ${rows.length} rows in sync`)
} else {
  writeFileSync(file, src, 'utf8')
  console.log(`gamebot fields: ${rows.length} rows written`)
}
