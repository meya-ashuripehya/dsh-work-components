# Generate src/calendar/glyphs.mjs — calendar CJK/Latin glyph masks (build-time; runtime needs no fonts).
# Fonts: Microsoft YaHei on Windows (or pass a TTF/TTC path). License: system font, glyphs are bitmaps we ship.
# Usage: python scripts/gen-calendar-glyphs.py [font.ttc|ttf] [out.mjs]
import base64, json, sys, zlib
from PIL import Image, ImageDraw, ImageFont

font_path = sys.argv[1] if len(sys.argv) > 1 else r'C:\Windows\Fonts\msyh.ttc'
out_path = sys.argv[2] if len(sys.argv) > 2 else 'src/calendar/glyphs.mjs'

# Fixed UI + lunar + jieqi + holidays + weather vocabulary. Event titles use these; unknown → skipped.
CHARS = (
  '0123456789'
  'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz'
  ' ./:+-–—_()[]「」·°%/℃~…'
  '年月日周一二三四五六七八九十廿冬腊正初闰休班今晴阴雨雪雾雷暴冰雹阵毛冻凇粒'
  '大中小强弱伴部朗多云未知开合'
  '立春水惊蛰分清明谷夏满芒至暑秋处白露寒霜降冬'
  '元旦春节劳动端午中秋国庆除夕元宵妇女青年儿童教师节'
  '成都北京上海重庆天津广州深圳杭州南京武汉西安成都'
  'Open-Meteo预报天气城市日程日历'
)

# de-dupe preserve order
seen = set()
chars = []
for ch in CHARS:
  if ch not in seen and not ch.isspace() or ch == ' ':
    # keep single space once
    if ch == ' ':
      if ' ' in seen: continue
    seen.add(ch)
    chars.append(ch)

out = {}

def mask(font, ch, box, baseline=False):
  img = Image.new('L', (box * 2, box * 2), 0)
  d = ImageDraw.Draw(img)
  d.text((box, box), ch, font=font, fill=255, anchor='ls' if baseline else 'mm')
  bb = img.getbbox()
  if not bb:
    return None
  img = img.crop(bb)
  w, h = img.size
  co = zlib.compressobj(9, zlib.DEFLATED, -15)
  data = co.compress(img.tobytes()) + co.flush()
  g = {'w': w, 'h': h, 'd': base64.b64encode(data).decode('ascii')}
  if baseline:
    g['oy'] = bb[1] - box
  return g

# YaHei TTC index 0 is usually Regular
try:
  font_ui = ImageFont.truetype(font_path, 22, index=0)
except TypeError:
  font_ui = ImageFont.truetype(font_path, 22)
try:
  font_sm = ImageFont.truetype(font_path, 16, index=0)
except TypeError:
  font_sm = ImageFont.truetype(font_path, 16)

for ch in chars:
  g = mask(font_ui, ch, 28, baseline=True)
  if g:
    out['k:' + ch] = g
  g2 = mask(font_sm, ch, 22, baseline=True)
  if g2:
    out['s:' + ch] = g2

src = [
  '/* Auto-generated by scripts/gen-calendar-glyphs.py — do not hand-edit. Bitmap masks only. */',
  'export const GLYPHS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')),
  '',
]
open(out_path, 'w', encoding='utf-8').write('\n'.join(src))
print('glyphs', len(out), 'chars', len(chars), 'bytes', sum(len(v['d']) for v in out.values()), '->', out_path)
